import os
import sys
import time
import uuid
import subprocess
import tkinter as tk
from tkinter import messagebox

from hypermarket_pos import HyperMarketPOS

# Constants
PROJECT_PATH = os.path.abspath(os.path.dirname(__file__))
VALIDATE_EXE = os.path.join(PROJECT_PATH, "validate.exe")
INPUT_FILE = os.path.join(PROJECT_PATH, "input.txt")
RESULT_FILE = os.path.join(PROJECT_PATH, "result.txt")

DOSBOX_CANDIDATES = [
    os.environ.get("DOSBOX_EXE", ""),
    r"C:\Program Files (x86)\DOSBox-0.74-3\DOSBox.exe",
    r"C:\Program Files (x86)\DOSBox-0.74\DOSBox.exe",
    r"C:\Program Files\DOSBox-0.74-3\DOSBox.exe",
    r"C:\Program Files\DOSBox-0.74\DOSBox.exe",
    r"C:\DOSBox\DOSBox.exe",
]


def find_dosbox():
    for p in DOSBOX_CANDIDATES:
        if p and os.path.isfile(p):
            return p
    return None


def run_validate_exe(dosbox_path):
    if not os.path.isfile(VALIDATE_EXE):
        return False, "Missing validate.exe in project directory."
    if not dosbox_path:
        return False, "DOSBox not found."

    cmd = [
        dosbox_path,
        "-noconsole",
        "-c", f"mount c \"{PROJECT_PATH}\"",
        "-c", "c:",
        "-c", "validate.exe",
        "-c", "exit",
    ]

    try:
        subprocess.run(cmd, cwd=PROJECT_PATH, timeout=20, check=True)
        return True, "OK"
    except subprocess.CalledProcessError as e:
        return False, f"validate.exe failed: {e}"
    except subprocess.TimeoutExpired:
        return False, "DOSBox timed out while running validate.exe."
    except Exception as e:
        return False, str(e)


class LoginWindow(tk.Tk):
    def __init__(self):
        super().__init__()
        self.title("HyperMarket Pro | Login")
        self.geometry("700x560")
        self._center_window(700, 560)
        self.configure(bg="#0a0b14")
        self.resizable(False, False)

        self.logged_in = False
        self.session_id = None

        self._build_ui()

    def _center_window(self, width, height):
        self.update_idletasks()
        screen_w = self.winfo_screenwidth()
        screen_h = self.winfo_screenheight()
        x = (screen_w - width) // 2
        y = (screen_h - height) // 2
        self.geometry(f"{width}x{height}+{x}+{y}")

    def _build_ui(self):
        frame = tk.Frame(self, bg="#1a2235", padx=24, pady=24)
        frame.place(relx=0.5, rely=0.5, anchor="center")

        tk.Label(frame, text="Customer Onboarding", font=("Impact", 30), fg="white", bg="#1a2235").pack(pady=(0, 14))

        tk.Label(frame, text="Full name", fg="#94a3b8", bg="#1a2235", anchor="w").pack(fill="x")
        self.entry_name = tk.Entry(frame, font=("Arial", 14), bg="#1e293b", fg="white", insertbackground="white")
        self.entry_name.pack(fill="x", pady=(0, 12), ipady=8)

        tk.Label(frame, text="Phone / Membership ID", fg="#94a3b8", bg="#1a2235", anchor="w").pack(fill="x")
        self.entry_phone = tk.Entry(frame, font=("Arial", 14), bg="#1e293b", fg="white", insertbackground="white")
        self.entry_phone.pack(fill="x", pady=(0, 12), ipady=8)

        self.lbl_status = tk.Label(frame, text="", fg="#10b981", bg="#1a2235")
        self.lbl_status.pack(pady=(0, 10))

        tk.Button(frame, text="Validate Details", font=("Arial", 11, "bold"), bg="#16a34a", fg="white", relief="flat", cursor="hand2", command=self.validate_user).pack(fill="x", pady=(0, 8), ipady=8)
        self.start_btn = tk.Button(frame, text="Initialize Session →", font=("Arial", 12, "bold"), bg="#6366f1", fg="white", relief="flat", state="disabled", cursor="hand2", command=self.start_session)
        self.start_btn.pack(fill="x", pady=(0, 4), ipady=10)

    def validate_user(self):
        name = self.entry_name.get().strip()
        phone = self.entry_phone.get().strip()
        if not name or not phone:
            messagebox.showerror("Validation", "Please fill all fields.")
            return

        try:
            with open(INPUT_FILE, "w", encoding="utf-8") as f:
                f.write(f"{name}\n{phone}\n")
        except Exception as e:
            messagebox.showerror("File Error", f"Could not write input.txt: {e}")
            return

        self.lbl_status.config(text="Running validate.exe via DOSBox...")
        dosbox = find_dosbox()
        ok, msg = run_validate_exe(dosbox)
        if not ok:
            self.lbl_status.config(text=f"Fallback validation (no DOSBox): {msg}", fg="#facc15")
            # Basic fallback: require non-empty fields
            self.start_btn.configure(state="normal")
            return

        self.after(750, self._check_result)

    def _check_result(self):
        if not os.path.isfile(RESULT_FILE):
            messagebox.showerror("Validation", "Result not generated by validate.exe.")
            self.lbl_status.config(text="Validation failed", fg="#ef4444")
            return

        try:
            with open(RESULT_FILE, "r", encoding="utf-8") as f:
                result = f.read().strip()
        except Exception as e:
            messagebox.showerror("Validation", f"Could not read result file: {e}")
            return

        if result == "1":
            self.lbl_status.config(text="Validation successful. You may start session.", fg="#22c55e")
            self.start_btn.configure(state="normal")
        else:
            messagebox.showerror("Validation", "Invalid Name or Phone.")
            self.lbl_status.config(text="Validation failed", fg="#ef4444")

    def start_session(self):
        self.session_id = str(uuid.uuid4())[:8]
        messagebox.showinfo("Session Started", f"Welcome {self.entry_name.get()}\nSession ID: {self.session_id}")
        self.logged_in = True
        self.destroy()


def main():
    login_window = LoginWindow()
    login_window.mainloop()

    if login_window.logged_in:
        HyperMarketPOS().mainloop()
    else:
        print("Login not completed. Exiting.")


if __name__ == "__main__":
    main()
